import type { ListingCard, ListingPrice } from '../../realestate/ingest.js';
import { isRecord, readPageProps, SsGePageShapeError, tbilisiWallClockToIso } from './page.js';

export { SsGePageShapeError };

/** What a full results page holds; a shorter page is the last one. */
export const RESULTS_PAGE_SIZE = 16;

const DAY_MS = 24 * 60 * 60 * 1000;
/**
 * How long a listing lives after its order time unless it is renewed. A
 * business's ends after 30 days (8 of 8 checked on detail pages, 2026-10-12;
 * in the first pass no agency listing outlived 30). One no business posted
 * ends after 45: 890 of about 960 such listings checked past their 30 days in
 * the first pass had exactly that (2026-10-15). Long-running exceptions
 * exist; the nightly detail check corrects those.
 */
function listingLifeMs(posterType: ListingCard['posterType']): number {
  return (posterType === 'unknown' ? 45 : 30) * DAY_MS;
}

/**
 * The site's own codes (guideline §4.3; the cottage code from 288 sampled
 * rows; commercial, land, hotel, daily rent and pledge from the live recon of
 * 2026-11-03, src/adapters/ss-ge/RECON_NOTES.md).
 */
const PROPERTY_TYPE_CODES: Readonly<Record<number, ListingCard['propertyType']>> = {
  5: 'flat',
  4: 'house',
  1: 'cottage',
  6: 'commercial',
  3: 'land',
  2: 'hotel',
};
const DEAL_TYPE_CODES: Readonly<Record<number, ListingCard['dealType']>> = {
  4: 'sale',
  1: 'rent',
  3: 'daily',
  2: 'pledge',
};
const CURRENCY_CODES: Readonly<Record<number, NonNullable<ListingCard['currencyPosted']>>> = {
  1: 'gel',
  2: 'usd',
};

const SMALLINT_MAX = 32_767;
const INTEGER_MAX = 2_147_483_647;
/**
 * Below the largest value each numeric column holds (src/db/schema/real-estate.ts):
 * area_m2 numeric(10, 2), the prices numeric(14, 2), the price per m² numeric(12, 2).
 * A poster's typo past these failed the insert and ended a whole run (an area
 * of 100,000,000 m², listing 37114086, 2026-10-26).
 */
const AREA_LIMIT = 1e8;
const PRICE_LIMIT = 1e12;
const PRICE_PER_M2_LIMIT = 1e10;
/** The title is generated by the site: "იყიდება 3 ოთახიანი ბინა ვერაზე". */
const ROOMS_RE = /(\d{1,2})\s*ოთახიანი/;
const WHOLE_NUMBER_RE = /^-?\d{1,3}$/;

export interface ResultsPage {
  /**
   * The site answered with another page than the one asked for. Past the end
   * of a list it serves page 1 with HTTP 200, so those rows are not this
   * page's and `cards` is empty.
   */
  pastEnd: boolean;
  servedPage: number;
  cards: ListingCard[];
  /** Rows on the page, skipped ones included. */
  rowCount: number;
  /** Rows of another kind or deal than the list being walked, or with no usable id or time. */
  skipped: number;
  /**
   * How many listings the site says the whole list can show
   * (`initialCardCount`), or null when it does not say. Its other counter,
   * `initialTotalApplicationCount`, also counts look-alikes the list folds
   * away (4,755 against 3,329 readable flats for daily rent, 2026-11-03;
   * guideline §4), so it is only the fallback. 0 with no rows on page 1 is an
   * empty list, which is normal for the smallest ones.
   */
  listTotal: number | null;
}

export interface ExpectedResultsPage {
  propertyType: ListingCard['propertyType'];
  dealType: ListingCard['dealType'];
  page: number;
}

/** A positive amount, or null: the site writes an unknown price, area or count as 0 or nothing. */
function positive(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) && value > 0 ? value : null;
}

/** A positive amount its column can hold, or null: past that it is a typo, and unknown. */
function bounded(value: unknown, limit: number): number | null {
  const amount = positive(value);
  return amount !== null && amount < limit ? amount : null;
}

/** The price block of a results row or a listing's own page; any amount it lacks is null. */
export function readListingPrice(value: unknown): ListingPrice {
  const price = isRecord(value) ? value : {};
  return {
    priceGel: bounded(price.priceGeo, PRICE_LIMIT),
    priceUsd: bounded(price.priceUsd, PRICE_LIMIT),
    pricePerM2Usd: bounded(price.unitPriceUsd, PRICE_PER_M2_LIMIT),
    pricePerM2Gel: bounded(price.unitPriceGeo, PRICE_PER_M2_LIMIT),
    currencyPosted: CURRENCY_CODES[Number(price.currencyType)] ?? null,
  };
}

function smallCount(value: unknown): number | null {
  const amount = positive(value);
  return amount !== null && Number.isInteger(amount) && amount <= SMALLINT_MAX ? amount : null;
}

/** A count where 0 is a real answer (no photos), or null when the row gives none. */
function countOrZero(value: unknown): number | null {
  return typeof value === 'number' && Number.isInteger(value) && value >= 0 && value <= SMALLINT_MAX
    ? value
    : null;
}

/** A whole number of listings, 0 included, or null. */
function countOrNone(value: unknown): number | null {
  return typeof value === 'number' && Number.isInteger(value) && value >= 0 ? value : null;
}

/** A yes or no only when the row says one; anything else is unknown. */
function flag(value: unknown): boolean | null {
  return typeof value === 'boolean' ? value : null;
}

export function reference(value: unknown): number | null {
  return typeof value === 'number' && Number.isInteger(value) && value > 0 && value <= INTEGER_MAX
    ? value
    : null;
}

/**
 * Control characters other than whitespace. Posters paste them in, and
 * Postgres refuses U+0000 in a text value: one such description ended a whole
 * run (listing 36827800, 2026-10-12).
 */
// biome-ignore lint/suspicious/noControlCharactersInRegex: matching them is the point
const CONTROL_RE = /[\u0000-\u0008\u000e-\u001f\u007f]/g;

export function text(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.replace(CONTROL_RE, '').trim();
  return trimmed === '' ? null : trimmed;
}

/**
 * Seven digits or more with at most three spaces, dots, dashes, slashes,
 * brackets or plus signs between each pair: a phone number however it is
 * spaced. A comma does not join digits, so "12, 14, 16" stays house numbers.
 */
const PHONE_RE = /\d(?:[\s./()+-]{0,3}\d){6,}/;

/**
 * The street and number are typed by the poster and shown on the public
 * site; some type their phone number there, or paste a whole advert. Such a
 * value is dropped whole (33 street numbers in the first pass, 2026-10-14).
 */
export function addressText(value: unknown): string | null {
  const plain = text(value);
  return plain === null || PHONE_RE.test(plain) ? null : plain;
}

/** One floor only. A list or a range ('7, 10, 11', '2-14') is one listing standing for several flats. */
function floor(value: unknown): number | null {
  if (typeof value === 'number') return Number.isInteger(value) ? value : null;
  if (typeof value !== 'string' || !WHOLE_NUMBER_RE.test(value.trim())) return null;
  return Number(value.trim());
}

/** Floors a listing can be on: below ground to the tallest towers, with room to spare. */
const FLOOR_BOUNDS = { min: -5, max: 200 };
/** One part of a floor list: a floor, or a range of them, a basement included ('-1-14'). */
const FLOOR_PART_RE = /^(-?\d{1,3})(?:\s*[-–]\s*(-?\d{1,3}))?$/;

/**
 * The lowest and highest floor a listing names (Phase 14A). One floor gives
 * both; a developer's list or range ('7, 10, 11, 13, 15', '2-14', '-1-14')
 * gives its ends, where `floor` gives nothing. Anything else is unknown.
 */
export function floorRange(value: unknown): { floorLow: number | null; floorHigh: number | null } {
  const unknown = { floorLow: null, floorHigh: null };
  let floors: number[];
  if (typeof value === 'number') {
    if (!Number.isInteger(value)) return unknown;
    floors = [value];
  } else if (typeof value === 'string' && value.trim() !== '') {
    floors = [];
    for (const part of value.split(',')) {
      const match = FLOOR_PART_RE.exec(part.trim());
      if (match?.[1] === undefined) return unknown;
      floors.push(Number(match[1]));
      if (match[2] !== undefined) floors.push(Number(match[2]));
    }
  } else {
    return unknown;
  }
  const floorLow = Math.min(...floors);
  const floorHigh = Math.max(...floors);
  if (floorLow < FLOOR_BOUNDS.min || floorHigh > FLOOR_BOUNDS.max) return unknown;
  return { floorLow, floorHigh };
}

/** ss.ge's name for a metro station, the same for every entrance of it: `medical_uni`, `samasi_aragveli`. */
const STATION_SLUG_RE = /^[a-z0-9_]{2,40}$/;
/** ss.ge's walking minutes come in fives up to 20; past an hour is not a walk. */
const STATION_MINUTES_MAX = 60;

/**
 * The metro stations ss.ge lists near a listing (Phase 14A), as station →
 * walking minutes. ss.ge works them out from the poster's map pin, so they
 * are only as good as the pin: kept as ss.ge said them, never shown as fact.
 * Each station is keyed by its name: ss.ge's `stationId` is one per entrance
 * (Isani is 81, 82 and 84), so the nearest entrance's minutes count. An empty
 * list says nothing (a listing 264 m from a station had none), so it is null.
 */
export function readMetro(value: unknown): Record<string, number> | null {
  if (!Array.isArray(value)) return null;
  const nearest = new Map<string, number>();
  for (const station of value) {
    if (!isRecord(station)) continue;
    const slug =
      typeof station.stationTitle === 'string' ? station.stationTitle.trim().toLowerCase() : '';
    const minutes = station.timeDistance;
    if (!STATION_SLUG_RE.test(slug)) continue;
    if (typeof minutes !== 'number' || !Number.isInteger(minutes)) continue;
    if (minutes < 1 || minutes > STATION_MINUTES_MAX) continue;
    const known = nearest.get(slug);
    if (known === undefined || minutes < known) nearest.set(slug, minutes);
  }
  if (nearest.size === 0) return null;
  return Object.fromEntries([...nearest].sort(([a], [b]) => a.localeCompare(b)));
}

const ENTITIES: Readonly<Record<string, string>> = {
  '&nbsp;': ' ',
  '&amp;': '&',
  '&lt;': '<',
  '&gt;': '>',
  '&quot;': '"',
  '&#39;': "'",
};

/** Descriptions are mostly plain text; some carry markup, which is dropped. */
function description(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const plain = value
    .replace(/<[^>]*>/g, ' ')
    .replace(/&(?:nbsp|amp|lt|gt|quot|#39);/g, (entity) => ENTITIES[entity] ?? ' ')
    .replace(/[<>]/g, ' ')
    .replace(CONTROL_RE, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return plain === '' ? null : plain;
}

function posterType(userInfo: unknown): ListingCard['posterType'] {
  // Present on rows posted by a business; absent says nothing, so never "owner".
  if (!isRecord(userInfo)) return 'unknown';
  return userInfo.userType === 3 ? 'developer' : 'agent';
}

function toCard(row: unknown, expected: ExpectedResultsPage): ListingCard | null {
  if (!isRecord(row)) return null;
  const id = reference(row.applicationId);
  const sourceUpdatedAt = tbilisiWallClockToIso(row.orderDate);
  if (id === null || sourceUpdatedAt === null) return null;
  if (PROPERTY_TYPE_CODES[Number(row.type)] !== expected.propertyType) return null;
  if (DEAL_TYPE_CODES[Number(row.dealType)] !== expected.dealType) return null;

  const address = isRecord(row.address) ? row.address : {};
  const poster = posterType(row.userInfo);
  const rooms = ROOMS_RE.exec(typeof row.title === 'string' ? row.title : '')?.[1];
  const streetNumber = addressText(address.streetNumber);
  const similarity = row.similarityGroup;

  return {
    sourceListingKey: String(id),
    canonicalUrl: `https://home.ss.ge/ka/udzravi-qoneba/${id}`,
    dealType: expected.dealType,
    propertyType: expected.propertyType,
    rooms: rooms === undefined ? null : smallCount(Number(rooms)),
    bedrooms: smallCount(row.numberOfBedrooms),
    areaM2: bounded(row.totalArea, AREA_LIMIT),
    floor: floor(row.floorNumber),
    totalFloors: smallCount(row.totalAmountOfFloor),
    ...readListingPrice(row.price),
    cityRef: reference(address.cityId),
    cityName: text(address.cityTitle),
    districtRef: reference(address.districtId),
    districtName: text(address.districtTitle),
    subdistrictRef: reference(address.subdistrictId),
    subdistrictName: text(address.subdistrictTitle),
    // Kept even when the street's name is dropped for holding a phone number.
    streetRef: reference(address.streetId),
    streetName: addressText(address.streetTitle),
    streetNumber: streetNumber === '0' ? null : streetNumber,
    ssMetro: readMetro(row.nearbySubwayStations),
    ...floorRange(row.floorNumber),
    posterType: poster,
    promoted: typeof row.vipStatus === 'number' && row.vipStatus > 0,
    // A sub-type code: 0 is the site's "none". An unknown code is kept, not dropped.
    commercialType: smallCount(row.commercialRealEstateType),
    landType: smallCount(row.landType),
    imageCount: countOrZero(row.imageCount),
    hasFurniture: flag(row.furniture),
    hasBuiltInKitchen: flag(row.withBuiltInKitchen),
    exclusive: row.isExclusive === true,
    videoViewing: row.hasRemoteViewing === true,
    description: description(row.description),
    similarityGroup:
      typeof similarity === 'number' || typeof similarity === 'string' ? String(similarity) : null,
    sourceUpdatedAt,
    sourceCreatedAt: tbilisiWallClockToIso(row.createDate),
    expectedEndAt: new Date(Date.parse(sourceUpdatedAt) + listingLifeMs(poster)).toISOString(),
  };
}

/**
 * Reads one results page of the list for `expected.propertyType` and
 * `expected.dealType`. No phone number, name or user id leaves this function:
 * only the fields named above are copied out of a row.
 */
export function parseResultsPage(html: string, expected: ExpectedResultsPage): ResultsPage {
  const pageProps = readPageProps(html);
  const list = isRecord(pageProps.applicationList)
    ? pageProps.applicationList.realStateItemModel
    : undefined;
  const servedPage = pageProps.initialPage;
  if (!Array.isArray(list) || typeof servedPage !== 'number') {
    throw new SsGePageShapeError('ss.ge results page has no listing list or page number');
  }
  const listTotal =
    countOrNone(pageProps.initialCardCount) ?? countOrNone(pageProps.initialTotalApplicationCount);

  if (servedPage !== expected.page) {
    return { pastEnd: true, servedPage, cards: [], rowCount: list.length, skipped: 0, listTotal };
  }

  const cards: ListingCard[] = [];
  for (const row of list) {
    const card = toCard(row, expected);
    if (card !== null) cards.push(card);
  }
  return {
    pastEnd: false,
    servedPage,
    cards,
    rowCount: list.length,
    skipped: list.length - cards.length,
    listTotal,
  };
}
